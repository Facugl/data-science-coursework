# Luna, Facundo

nombre_completo = str(input("Ingrese el nombre completo:"))

minusculas = nombre_completo.lower()
mayusculas = nombre_completo.upper()
primera_mayuscula = nombre_completo.capitalize()

print(f"Minúsculas: {minusculas}")
print(f"Mayúsculas: {mayusculas}")
print(f"Primera letra en mayúscula: {primera_mayuscula}")
